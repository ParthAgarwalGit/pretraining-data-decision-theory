"""Calibrated checks of 3-seed noise estimates against a many-seed reference (N7-10 S2).

With n seeds per cell (PolyPythia: 10), the 3-seed SD estimate is compared with the
n-seed SD over all C(n, 3) seed subsets. Its error is large even for ideal Gaussian
noise (with 3 seeds, E|s/sigma - 1| is about 0.39), so the criterion is calibrated: the
observed statistic is compared with its exact Monte-Carlo null under i.i.d. Gaussian
seed noise, generated by the SAME subsetting procedure. The statistic is scale-free, so
the null does not depend on sigma. Rejection means the 3-seed estimates are worse than
Gaussian theory predicts, e.g. because of heavy tails or outlier seeds.
"""

from __future__ import annotations

import itertools

import numpy as np
from scipy import stats


def subset_sd_error(x: np.ndarray, k: int = 3) -> np.ndarray:
    """Mean over all k-of-n seed subsets of |sd_k / sd_n - 1| (ddof=1), for the last axis.

    ``x`` has shape (..., n). Cells whose n-seed SD is 0 return NaN.
    """
    x = np.asarray(x, dtype=float)
    n = x.shape[-1]
    combos = np.array(list(itertools.combinations(range(n), k)))
    sd_n = np.std(x, axis=-1, ddof=1)
    sd_k = np.std(x[..., combos], axis=-1, ddof=1)  # (..., n_combos)
    with np.errstate(divide="ignore", invalid="ignore"):
        err = np.mean(np.abs(sd_k / sd_n[..., None] - 1.0), axis=-1)
    return np.where(sd_n > 0, err, np.nan)


def gaussian_null_of_median(
    n_cells: int, n_seeds: int, k: int = 3, n_sim: int = 20000, seed: int = 0, chunk: int = 2000
) -> np.ndarray:
    """Monte-Carlo null distribution of the median over ``n_cells`` of ``subset_sd_error``
    under i.i.d. Gaussian seed noise."""
    rng = np.random.default_rng(seed)
    out = []
    for start in range(0, n_sim, chunk):
        m = min(chunk, n_sim - start)
        sims = rng.standard_normal((m, n_cells, n_seeds))
        out.append(np.median(subset_sd_error(sims, k), axis=1))
    return np.concatenate(out)


def calibrated_sd_check(
    cells: np.ndarray, k: int = 3, n_sim: int = 20000, seed: int = 0, level: float = 0.95
) -> dict:
    """S2a. ``cells`` is (n_cells, n_seeds). Passes when the observed median-over-cells
    statistic is at most the ``level`` quantile of its Gaussian null (one-sided)."""
    cells = np.asarray(cells, dtype=float)
    per_cell = subset_sd_error(cells, k)
    valid = ~np.isnan(per_cell)
    obs = float(np.median(per_cell[valid]))
    null = gaussian_null_of_median(int(valid.sum()), cells.shape[1], k, n_sim, seed)
    q = float(np.quantile(null, level))
    return {
        "per_cell": per_cell.tolist(),
        "n_cells_used": int(valid.sum()),
        "observed_median": obs,
        "null_median": float(np.median(null)),
        "null_quantile": q,
        "level": level,
        "p_value_one_sided": float((1 + np.sum(null >= obs)) / (1 + len(null))),
        "passed": bool(obs <= q),
    }


def shapiro_check(cells: np.ndarray, alpha: float = 0.01, min_share: float = 0.80) -> dict:
    """S2b. Shapiro-Wilk on each cell's seed scores; passes when p > alpha in at least
    ``min_share`` of cells with non-zero spread."""
    ps = []
    for row in np.asarray(cells, dtype=float):
        ps.append(float(stats.shapiro(row).pvalue) if np.std(row) > 0 else float("nan"))
    ps_arr = np.array(ps)
    valid = ~np.isnan(ps_arr)
    share = float(np.mean(ps_arr[valid] > alpha)) if valid.any() else float("nan")
    return {"p_values": ps, "share_above_alpha": share, "passed": bool(share >= min_share)}
